const templateSource = `---
const { name, items } = Astro.props;
---
<main><h1>{name}</h1><ul>{items.map((item) => <li>{item}</li>)}</ul></main>`;

const publicBuildCall = `import { precompile } from 'sikka/precompile';

const result = precompile(templateSource, {
  id: '/src/views/Greeting.astro',
  resolveComponent(specifier, importer) {
    // The build host owns file I/O and turns Template imports into output modules.
    return specifier.replace(/\\.astro$/, '.sikka.mjs');
  },
});

await host.write('/dist/views/Greeting.sikka.mjs', result.code);
// result.dependencies lets the host visit imported Components.`;

const generatedModule = `// Generated by sikka/precompile — do not edit.
import { createPrecompiledTemplate, escapeHtml } from 'sikka/precompiled-runtime';

const components = {};
const options = { autoEscape: true };

function renderSync(props, slots = {}) {
  let __out = '';
  const Astro = { props, slots };
  const { name, items } = Astro.props;
  __out += '<main><h1>';
  __out += escapeHtml(name);
  __out += '</h1><ul>';
  for (const item of items) __out += '<li>' + escapeHtml(item) + '</li>';
  __out += '</ul></main>';
  return __out;
}

export async function* stream(props, slots = {}) {
  // The emitted body has the same Rendered HTML semantics as renderSync.
  yield renderSync(props, slots);
}

export default createPrecompiledTemplate({ renderSync, stream, components, options });`;

const consumerCall = `import Greeting, { stream } from './dist/views/Greeting.sikka.mjs';

const html = Greeting.renderSync({
  name: 'Ada & <Lin>',
  items: ['one', 'two'],
});
// '<main><h1>Ada &amp; &lt;Lin&gt;</h1><ul><li>one</li><li>two</li></ul></main>'

for await (const chunk of stream({ name: 'Ada', items: [] })) {
  send(chunk);
}`;

